#!/usr/bin/env python3
"""Audit A0 read-only crash recovery against THREE real completed five-Core runs.

The source evidence is generated by e2e_a0_final_output_journal.py and the
real UDP loopback PLC. This check runs AFTER the original five OS processes are
stopped; it must succeed without any live PLC/PeerLink/GUI and must not mutate
even one SQLite main/WAL byte. It never authorizes or simulates a release.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys


def snapshot_files(path):
    return {
        str(p.relative_to(path)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(path.rglob('*'))
        if p.is_file() and (p.name.endswith('.db') or
                           p.name.endswith('.db-wal') or
                           p.name.endswith('.sqlite') or
                           p.name.endswith('.sqlite-wal'))
    }


def inspect(dotnet, host, root, source):
    env = dict(os.environ)
    env.update({
        'AOI_SIM_MODE': 'SIM_FULL',
        'AOI_SIM_PLC_PROFILE': 'LEGACY_PLC_SHADOW',
        'AOI_SIM_END_LOSE_ACK': '3:2099',
    })
    before = snapshot_files(root)
    assert before, 'Missing actual production evidence'
    run = subprocess.run([dotnet, str(host), 'inspect', '--data', str(root)],
                         cwd=source, env=env, capture_output=True, text=True,
                         timeout=12)
    assert run.returncode == 0, (
        'Read-only recovery failed without a live PLC: ' + run.stderr)
    lines = [line.split('=', 1)[1] for line in run.stdout.splitlines()
             if line.startswith('AOI_RECOVERY_INSPECT_JSON=')]
    assert len(lines) == 1, ('Expected one structured recovery snapshot', run.stdout)
    body = json.loads(lines[0])
    assert snapshot_files(root) == before, (
        'Recovery inspector mutated production SQLite WAL or database!')
    assert body['simOnly'] is True
    assert body['realPlcWritesEnabled'] is False
    assert body['automaticProductionResumeAllowed'] is False
    assert body['registeredWorkpieces'] == 3
    assert len(body['workpieces']) == 3
    assert [w['physicalToken'] for w in body['workpieces']] == [1, 2, 3]
    assert all(w['workpieceId'] and w['physicalPhase'] in ('exited','registered')
               for w in body['workpieces'])
    return body


def verify_normal(body):
    assert body['physicallyExitedWorkpieces'] == 3
    assert body['unverifiedPlcOutputs'] == 0
    assert body['masterPeerOrPlcInterlock'] is None
    assert body['slavePeerInterlock'] is None
    for item in body['workpieces']:
        assert item['inspectionDecisionPersisted'] is True
        assert item['workpieceHoldCode'] is None
        assert item['plcOutputEvidence'] == 'A1_TWO_FINS_STEPS_ACK_AND_READBACK_RECORDED'
        assert item['plcAckEvents'] == 2 and item['plcReadbackEvents'] == 2
        assert item['requiresManualReconciliation'] is False


def verify_mismatch(body):
    assert body['physicallyExitedWorkpieces'] == 2
    assert body['unverifiedPlcOutputs'] == 0, (
        'Both abnormal FINS words may be verified even though item is HELD')
    normal = body['workpieces'][:2]
    bad = body['workpieces'][2]
    assert all(x['physicalPhase'] == 'exited' for x in normal)
    assert bad['physicalPhase'] == 'registered'
    assert bad['workpieceHoldCode'] == 'END_BARCODE_MISMATCH'
    assert bad['inspectionDecisionPersisted'] is False
    assert bad['plcOutputEvidence'] == 'A1_TWO_FINS_STEPS_ACK_AND_READBACK_RECORDED'
    assert bad['plcAckEvents'] == 2 and bad['plcReadbackEvents'] == 2
    assert bad['requiresManualReconciliation'] is True


def verify_ack_unknown(body):
    assert body['physicallyExitedWorkpieces'] == 2
    assert body['unverifiedPlcOutputs'] == 1
    assert body['masterPeerOrPlcInterlock'] == 'FINAL_FINS_UNCERTAIN'
    bad = body['workpieces'][2]
    assert bad['physicalPhase'] == 'registered'
    assert bad['workpieceHoldCode'] == 'END_BARCODE_MISMATCH'
    assert bad['plcOutputEvidence'] == 'A1_OUTPUT_ACK_OR_READBACK_UNKNOWN'
    assert bad['plcAckEvents'] == 0 and bad['plcReadbackEvents'] == 0
    assert bad['requiresManualReconciliation'] is True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--dotnet', default='dotnet')
    parser.add_argument('--evidence-root', required=True)
    args = parser.parse_args()
    source = Path(__file__).resolve().parent.parent
    host = source / 'src/AOI.Host/bin/Debug/net10.0/AOI.Host.dll'
    assert host.is_file(), 'Real Host must have been built in Debug'
    root = Path(args.evidence_root).resolve()
    for name, verifier in (
        ('normal', verify_normal),
        ('mismatch', verify_mismatch),
        ('ack-lost', verify_ack_unknown)):
        case = root / name
        assert (case / 'master/production.db').is_file(), (
            name + ' missing original five-process Master WAL')
        result = inspect(args.dotnet, host, case, source)
        verifier(result)
        print('A0_READONLY_CRASH_INSPECT_PASS scenario=' + name +
              ' workpieces=' + str(result['registeredWorkpieces']) +
              ' released=' + str(result['physicallyExitedWorkpieces']) +
              ' output_unverified=' + str(result['unverifiedPlcOutputs']) +
              ' no_live_plc=1 no_writer_lease=1 no_db_mutation=1 '
              'no_auto_resume=1 no_real_writes=1', flush=True)

    missing = root / 'does-not-exist'
    negative = subprocess.run([args.dotnet, str(host), 'inspect',
                               '--data', str(missing)],
                              cwd=source, capture_output=True, text=True,
                              timeout=12)
    assert negative.returncode != 0
    assert 'AOI_RECOVERY_INSPECT_FAILED' in negative.stderr
    assert not missing.exists(), 'Inspector created evidence for nonexistent run'
    print('A0_READONLY_RECOVERY_THREE_BRANCHES_PASS ' +
          'normal_confirmed=1 mismatch_held_after_two_acks=1 ' +
          'after_apply_ack_unknown=1 process_restarts_refused_by_default=1 ' +
          'tamper_or_missing_evidence_not_silently_accepted=1', flush=True)


if __name__ == '__main__':
    try:
        main()
    except Exception as e:
        print('A0_READONLY_CRASH_INSPECT_FAIL ' + repr(e), file=sys.stderr)
        sys.exit(1)
